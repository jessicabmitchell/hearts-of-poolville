// Words for the public forms, in English and Spanish. To change what a form says, edit both
// languages here. Have a native Spanish speaker look over the Spanish before each season.

export type Lang = 'en' | 'es';

/** Spanish when the page URL has ?lang=es, English otherwise. */
export function toLang(value: unknown): Lang {
  return value === 'es' ? 'es' : 'en';
}

/** Turn '2026-11-15' into "November 15" or "15 de noviembre". */
export function formatDay(isoDate: string, lang: Lang): string {
  return new Intl.DateTimeFormat(lang === 'es' ? 'es-US' : 'en-US', {
    month: 'long',
    day: 'numeric',
    timeZone: 'UTC',
  }).format(new Date(`${isoDate}T12:00:00Z`));
}

/** Turn several dates into "December 20, December 21, or December 22". */
export function formatDayChoices(isoDates: string[], lang: Lang): string {
  return new Intl.ListFormat(lang === 'es' ? 'es-US' : 'en-US', { type: 'disjunction' }).format(
    isoDates.map((d) => formatDay(d, lang)),
  );
}

